"""Regenerate examples/ from the test fixtures.

Run from the repository root:  python scripts/generate_examples.py
CI fails if the committed examples differ from what this produces.
"""

import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, ROOT)

from android_agent_playbook import cli  # noqa: E402
from tests import fixtures  # noqa: E402

EXAMPLES = (
    ("compose-hilt", fixtures.COMPOSE_HILT,
     "Multi-module Compose app: Kotlin DSL, version catalog, convention plugins, Hilt, Room, ktlint"),
    ("views-compose-groovy", fixtures.VIEWS_COMPOSE_GROOVY,
     "Legacy XML Views app adopting Compose: Groovy DSL, Koin, kapt, no version catalog"),
    ("kmp", fixtures.KMP,
     "Kotlin Multiplatform with Compose Multiplatform, Koin and SQLDelight"),
)
# Playbooks and command wrappers are the same for every project, so only the
# project-specific files are kept here. See src/android_agent_playbook/templates/skills/.
KEEP = ("AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md",
        ".cursor/rules/android-agent-playbook.mdc")


def main():
    out_root = os.path.join(ROOT, "examples")
    index = [
        "# Examples",
        "",
        "Output of `android-agent-playbook install` on the small fixture projects in",
        "[`tests/fixtures.py`](../tests/fixtures.py). Generated by",
        "`python scripts/generate_examples.py`; CI fails if they are stale.",
        "",
        "The five playbooks (`.agents/skills/`) and the Claude Code and Cursor command",
        "wrappers are identical in every project, so they are not repeated here. See",
        "[`templates/skills/`](../src/android_agent_playbook/templates/skills/).",
        "",
        "| Example | Project | Detected | Preset |",
        "| --- | --- | --- | --- |",
    ]
    for name, files, description in EXAMPLES:
        project = fixtures.make(files)
        try:
            info = cli.detect(project)
            preset = info["preset"]
            for target in cli.build_targets(info, preset, list(cli.AGENTS)):
                if target.path not in KEEP:
                    continue
                _, text = cli.apply_block(None, target)
                dest = os.path.join(out_root, name, *target.path.split("/"))
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                with open(dest, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
            index.append("| [`%s`](%s/AGENTS.md) | %s | %s | `%s` |" % (
                name, name, description, cli.summarize(info), preset))
        finally:
            shutil.rmtree(project)
    with open(os.path.join(out_root, "README.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(index) + "\n")
    print("examples/ regenerated (%d projects)" % len(EXAMPLES))


if __name__ == "__main__":
    main()
